/**
 * 同一キーに対する処理を、同一サーバーインスタンス内でFIFOに直列化するための簡易ロック。
 *
 * 【保存先】
 * このモジュールのトップレベルにある `queues`（Map）のみ。Node.jsプロセスの
 * メモリ（ヒープ）上に存在するだけで、DBやファイル、外部サービスへは一切保存しない。
 * 新しい外部サービスの契約・追加インフラは不要（既存のNode.js実行環境のみで動く）。
 *
 * 【キー】
 * 呼び出し元（app/api/bookings/route.ts）が渡す `studio:<date>` という
 * 日付単位の文字列。1つのスタジオ（予約可能な資源は1つ）を前提に、
 * 同じ日の予約処理はすべて同じキューに入れて直列化する。
 * 以前は `${date}T${time}`（開始時刻まで含む）をキーにしていたが、
 * それでは「13:00〜16:00」と「14:00〜17:00」のように開始時刻が異なるが
 * 時間帯が重なるリクエストが別々のキューに分かれてしまい、
 * 両方が同時に「空いている」と判定され得た。日付単位に広げたことで、
 * 同じ日のどの時間帯への予約リクエストも同一キューで順番に処理される。
 *
 * 【有効範囲（重要な限界）】
 * これはNode.jsプロセス内メモリのみのロックであり、次の場合は共有されない。
 *   - Vercel等で複数のサーバーインスタンス（別プロセス）が並行稼働している場合
 *     （同時アクセスが増えるとVercelは複数インスタンスを起動し得る）
 *   - サーバーレス関数のコールドスタート・再起動（プロセスが変われば空のMapから始まる）
 *   - 複数リージョンにデプロイされている場合
 * 同一プロセス内であれば完全に直列化されるが、プロセスをまたいだ排他は一切できない。
 * 複数インスタンス間でも確実に排他したい場合は、DBやRedis等の外部ロックが必要になるが、
 * 今回は新規の外部サービス契約を行わないため、既存のGoogleカレンダーへの
 * 「登録直前の空き再確認」（lib/google-calendar.ts の isSlotStillAvailable）を
 * 多重防御として残している。これにより、別プロセスからの重複リクエストでも、
 * 先に登録が完了していればその後のリクエストは空き無しと判定されやすくなるが、
 * ほぼ同時の場合は完全には防げない（詳細はREADME/変更記録を参照）。
 */
const queues = new Map<string, Promise<unknown>>()

export function runExclusive<T>(key: string, fn: () => Promise<T>): Promise<T> {
  const prior = queues.get(key) ?? Promise.resolve()
  const run = prior.then(fn, fn)
  // 失敗しても後続の処理を止めないよう、キュー自体はcatchして保持する
  queues.set(key, run.catch(() => {}))
  return run
}
